using System.Text.RegularExpressions;
using RunSignal.Alerting;
using RunSignal.Prometheus;

namespace RunSignal.Tests;

// runsignal export grafana-alerts: Grafana-managed rules with the same PromQL as the Prometheus rules.
public sealed partial class GrafanaAlertingTests
{
    private static readonly WorkloadManifest s_manifest = new()
    {
        Service = "billing",
        Workloads =
        [
            new WorkloadManifestEntry { Name = "nightly-invoice", Schedule = "0 2 * * *", MaxDurationSeconds = 1800, MinProcessed = 100, Severity = Severity.Critical, Owner = "billing-team", RunbookUrl = "https://wiki.example.com/runbooks?job=invoice&env=prod" },
            new WorkloadManifestEntry { Name = "stock-sync", ExpectEverySeconds = 300, FailureRateThreshold = 0.2 },
        ],
    };

    private static string Generate() => GrafanaAlerting.Generate([s_manifest], new AlertOptions(), "prom-uid", "RunSignal", out _);

    [Fact]
    public void Every_prometheus_rule_becomes_a_grafana_rule_with_the_same_query()
    {
        var yaml = Generate();
        var rules = PrometheusRules.Rules([s_manifest], new AlertOptions(), out _);

        Assert.StartsWith("# Generated by RunSignal", yaml, StringComparison.Ordinal);
        Assert.Contains("apiVersion: 1", yaml);
        Assert.Equal(rules.Count, UidPattern().Matches(yaml).Count);
        foreach (var rule in rules)
            Assert.Contains("              expr: '" + rule.Expr.Replace("'", "''", StringComparison.Ordinal) + "'", yaml);
        Assert.Equal(rules.Count, yaml.Split("datasourceUid: 'prom-uid'").Length - 1);
        Assert.Contains("    folder: 'RunSignal'", yaml);
    }

    [Fact]
    public void Uids_are_unique_and_stable_so_provisioning_again_updates_the_rules()
    {
        var uids = UidPattern().Matches(Generate()).Select(m => m.Value).ToList();

        Assert.Equal(uids.Count, uids.Distinct().Count());
        Assert.All(uids, uid => Assert.InRange(uid.Length - "uid: ".Length, 1, 40));
        Assert.Equal(uids, UidPattern().Matches(Generate()).Select(m => m.Value));
    }

    [Fact]
    public void Owner_and_runbook_reach_the_labels_and_annotations()
    {
        var yaml = Generate();

        Assert.Contains("          owner: 'billing-team'", yaml);
        Assert.Contains("          runbook_url: 'https://wiki.example.com/runbooks?job=invoice&env=prod'", yaml);
        Assert.Contains("        noDataState: OK", yaml);
    }

    [Fact]
    public void Manifests_of_one_service_share_a_rule_group()
    {
        var other = s_manifest with { Workloads = [new WorkloadManifestEntry { Name = "cleanup", Schedule = "0 4 * * *" }] };
        var yaml = GrafanaAlerting.Generate([s_manifest, other], new AlertOptions(), "prom-uid", "RunSignal", out _);

        Assert.Single(Regex.Matches(yaml, "name: 'runsignal-billing'"));
        Assert.Contains("billing/cleanup: missed", yaml);
    }

    [GeneratedRegex(@"uid: runsignal-[0-9a-f]+")]
    private static partial Regex UidPattern();
}
