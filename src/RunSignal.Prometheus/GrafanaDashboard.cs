using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Text.Json.Nodes;

namespace RunSignal.Prometheus;

/// <summary>
/// Writes a Grafana dashboard for RunSignal metrics in Prometheus, the counterpart of the New Relic dashboard:
/// runs by outcome, time since each workload's last success and heartbeat, p95 duration, items processed, failures
/// by error type and the RunSignal alerts that are firing. Uses the same metric names as <see cref="PrometheusRules"/>.
/// </summary>
public static class GrafanaDashboard
{
    private const string Filter = "job=~\"$job\", runsignal_workload=~\"$workload\"";

    /// <summary>
    /// Generates the dashboard JSON, ready for Grafana's import or provisioning. With manifests, the dashboard is
    /// named after their services and selects them by default; without, it shows every service that reports.
    /// </summary>
    public static string Generate(IEnumerable<WorkloadManifest> manifests)
    {
        ArgumentNullException.ThrowIfNull(manifests);
        var services = manifests.Select(m => m.Service).Distinct(StringComparer.Ordinal).Order(StringComparer.Ordinal).ToList();

        var dashboard = new JsonObject
        {
            ["uid"] = Uid(services),
            ["title"] = services.Count == 0 ? "RunSignal" : "RunSignal: " + string.Join(", ", services),
            ["description"] = "Generated by RunSignal. Regenerate with `runsignal export grafana`.",
            ["tags"] = new JsonArray("runsignal", "background-jobs"),
            ["timezone"] = "browser",
            ["schemaVersion"] = 39,
            ["refresh"] = "1m",
            ["time"] = new JsonObject { ["from"] = "now-24h", ["to"] = "now" },
            ["templating"] = new JsonObject
            {
                ["list"] = new JsonArray(
                    new JsonObject
                    {
                        ["name"] = "datasource",
                        ["label"] = "Data source",
                        ["type"] = "datasource",
                        ["query"] = "prometheus",
                    },
                    Variable("job", "Service", "label_values({__name__=~\"runsignal_workload_.*\"}, job)", services),
                    Variable("workload", "Workload", "label_values({__name__=~\"runsignal_workload_.*\", job=~\"$job\"}, runsignal_workload)", [])),
            },
            ["panels"] = new JsonArray(
                Panel(1, "Runs in the last hour", "stat", 0, 0, 6, 6, "short",
                    ("{{runsignal_outcome}}", $"sum by (runsignal_outcome) (increase(runsignal_workload_runs_total{{{Filter}}}[1h]))")),
                Panel(2, "Firing RunSignal alerts", "table", 6, 0, 18, 6, "short",
                    ("", "count by (job, runsignal_workload, runsignal_alert, severity) (ALERTS{alertstate=\"firing\", runsignal_alert!=\"\", " + Filter + "})"),
                    instant: true),
                Panel(3, "Runs by outcome", "timeseries", 0, 6, 12, 8, "short",
                    ("{{runsignal_workload}} {{runsignal_outcome}}", $"sum by (runsignal_workload, runsignal_outcome) (increase(runsignal_workload_runs_total{{{Filter}}}[$__rate_interval]))")),
                Panel(4, "Run duration (p95)", "timeseries", 12, 6, 12, 8, "s",
                    ("{{runsignal_workload}}", $"histogram_quantile(0.95, sum by (runsignal_workload, le) (rate(runsignal_workload_duration_seconds_bucket{{{Filter}}}[$__rate_interval])))")),
                Panel(5, "Time since last success", "timeseries", 0, 14, 12, 8, "s",
                    ("{{runsignal_workload}}", $"max by (runsignal_workload) (runsignal_workload_since_success_seconds{{{Filter}}})")),
                Panel(6, "Time since last heartbeat", "timeseries", 12, 14, 12, 8, "s",
                    ("{{runsignal_workload}}", $"max by (runsignal_workload) (runsignal_workload_since_heartbeat_seconds{{{Filter}}})")),
                Panel(7, "Items processed and failed", "timeseries", 0, 22, 12, 8, "short",
                    ("{{runsignal_workload}} {{runsignal_item_result}}", $"sum by (runsignal_workload, runsignal_item_result) (increase(runsignal_workload_items_total{{{Filter}}}[$__rate_interval]))")),
                Panel(8, "Failed runs by error type (24h)", "table", 12, 22, 12, 8, "short",
                    ("", $"sum by (runsignal_workload, error_type) (increase(runsignal_workload_runs_total{{{Filter}, runsignal_outcome=\"failure\"}}[24h])) > 0"),
                    instant: true)),
        };

        using var stream = new MemoryStream();
        using (var writer = new Utf8JsonWriter(stream, new JsonWriterOptions { Indented = true }))
            dashboard.WriteTo(writer);
        return Encoding.UTF8.GetString(stream.ToArray()) + "\n";
    }

    // Grafana identifies dashboards by uid, so the same services always produce the same uid and re-importing
    // replaces the dashboard instead of adding a copy.
    private static string Uid(IReadOnlyList<string> services)
    {
        if (services.Count == 0)
            return "runsignal";
        var hash = SHA256.HashData(Encoding.UTF8.GetBytes(string.Join("\n", services)));
        return "runsignal-" + Convert.ToHexString(hash, 0, 6).ToLowerInvariant();
    }

    private static JsonObject Variable(string name, string label, string query, IReadOnlyList<string> selected)
    {
        var current = selected.Count == 0
            ? new JsonObject { ["text"] = "All", ["value"] = new JsonArray("$__all") }
            : new JsonObject { ["text"] = new JsonArray([.. selected.Select(s => (JsonNode)s)]), ["value"] = new JsonArray([.. selected.Select(s => (JsonNode)s)]) };
        return new JsonObject
        {
            ["name"] = name,
            ["label"] = label,
            ["type"] = "query",
            ["datasource"] = Datasource(),
            ["query"] = new JsonObject { ["query"] = query, ["refId"] = name },
            ["refresh"] = 2,
            ["multi"] = true,
            ["includeAll"] = true,
            ["allValue"] = ".*",
            ["sort"] = 1,
            ["current"] = current,
        };
    }

    private static JsonObject Panel(int id, string title, string type, int x, int y, int w, int h, string unit,
        (string Legend, string Expr) target, bool instant = false) => new()
    {
        ["id"] = id,
        ["title"] = title,
        ["type"] = type,
        ["datasource"] = Datasource(),
        ["gridPos"] = new JsonObject { ["x"] = x, ["y"] = y, ["w"] = w, ["h"] = h },
        ["fieldConfig"] = new JsonObject { ["defaults"] = new JsonObject { ["unit"] = unit }, ["overrides"] = new JsonArray() },
        ["targets"] = new JsonArray(new JsonObject
        {
            ["refId"] = "A",
            ["datasource"] = Datasource(),
            ["expr"] = target.Expr,
            ["legendFormat"] = target.Legend.Length == 0 ? "__auto" : target.Legend,
            ["instant"] = instant,
            ["range"] = !instant,
            ["format"] = instant ? "table" : "time_series",
        }),
    };

    private static JsonObject Datasource() => new() { ["type"] = "prometheus", ["uid"] = "${datasource}" };
}
