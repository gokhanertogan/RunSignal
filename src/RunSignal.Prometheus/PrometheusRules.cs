using System.Globalization;
using System.Text;
using RunSignal.Alerting;

namespace RunSignal.Prometheus;

/// <summary>One RunSignal alerting rule in PromQL, before it is written for a particular ruler.</summary>
/// <param name="Service">The service the workload belongs to.</param>
/// <param name="Workload">The workload and its expectations.</param>
/// <param name="Alert">The alert name, such as <c>RunSignalMissed</c>.</param>
/// <param name="Kind">The alert kind, such as <c>missed</c>; the <c>runsignal_alert</c> label.</param>
/// <param name="Expr">The PromQL expression. It returns a series while the alert condition holds, and nothing otherwise.</param>
/// <param name="For">How long the condition must hold before the alert fires, such as <c>1m</c>.</param>
/// <param name="Description">What the alert means, for its description annotation.</param>
public sealed record AlertRule(string Service, WorkloadManifestEntry Workload, string Alert, string Kind, string Expr, string For, string Description);

/// <summary>
/// Turns workload manifests into a Prometheus alerting rules file. Metric and label names are the ones Prometheus
/// gives OpenTelemetry metrics received over OTLP with its default translation: dots become underscores, units
/// and <c>_total</c> are appended, and <c>service.name</c> becomes the <c>job</c> label.
/// </summary>
public static class PrometheusRules
{
    private const string Runs = "runsignal_workload_runs_total";
    private const string Items = "runsignal_workload_items_total";
    private const string DurationBucket = "runsignal_workload_duration_seconds_bucket";
    private const string SinceSuccess = "runsignal_workload_since_success_seconds";
    private const string SinceHeartbeat = "runsignal_workload_since_heartbeat_seconds";
    private const string ActiveRunAge = "runsignal_workload_active_run_age_seconds";
    private const string By = "sum by (job, runsignal_workload)";

    /// <summary>Generates the rules file. <paramref name="warnings"/> lists expectations that produced no rule, and why.</summary>
    public static string Generate(IEnumerable<WorkloadManifest> manifests, AlertOptions options, out IReadOnlyList<string> warnings)
    {
        ArgumentNullException.ThrowIfNull(manifests);
        ArgumentNullException.ThrowIfNull(options);
        var notes = new List<string>();
        var yaml = new StringBuilder()
            .AppendLine("# Generated by RunSignal from workload manifests. Do not edit: regenerate with `runsignal export prometheus`.")
            .AppendLine("groups:");

        foreach (var manifest in manifests)
        {
            yaml.Append("  - name: ").AppendLine(Yaml($"runsignal-{manifest.Service}"));
            var rules = Rules([manifest], options, out var found);
            notes.AddRange(found);
            if (rules.Count == 0)
                continue;
            yaml.AppendLine("    rules:");
            foreach (var rule in rules)
                Append(yaml, rule);
        }
        warnings = notes;
        return yaml.ToString();
    }

    /// <summary>
    /// The alerting rules for the manifests, for any Prometheus-compatible ruler or Grafana-managed alerting.
    /// <paramref name="warnings"/> lists expectations that produced no rule, and why.
    /// </summary>
    public static IReadOnlyList<AlertRule> Rules(IEnumerable<WorkloadManifest> manifests, AlertOptions options, out IReadOnlyList<string> warnings)
    {
        ArgumentNullException.ThrowIfNull(manifests);
        ArgumentNullException.ThrowIfNull(options);
        var rules = new List<AlertRule>();
        var notes = new List<string>();
        foreach (var manifest in manifests)
        {
            foreach (var workload in manifest.Workloads)
                AddRules(rules, manifest.Service, workload, options, notes);
        }
        warnings = notes;
        return rules;
    }

    private static void AddRules(List<AlertRule> rules, string service, WorkloadManifestEntry w, AlertOptions options, List<string> warnings)
    {
        var selector = $"job={Label(service)}, runsignal_workload={Label(w.Name)}";
        var notReporting = $"{(int)options.NotReportingAfter.TotalMinutes}m";
        var perRun = w.Reporting == WorkloadReporting.PerRun;
        var count = 0;

        // How much a counter grew within a window. A long-running process keeps one series, so increase() works.
        // Per-run workloads export each run as its own series (a new service.instance.id), which increase() cannot
        // see grow from a single process; the run's final value is its whole contribution, so sum those instead.
        string Grew(string series, string window) => perRun
            ? $"{By} (max_over_time({series}[{window}]))"
            : $"{By} (increase({series}[{window}]))";
        void Rule(string alert, string kind, string expr, string forDuration, string summary)
        {
            rules.Add(new AlertRule(service, w, alert, kind, expr, forDuration, summary));
            count++;
        }

        if (w.Schedule is not null)
        {
            try
            {
                var missed = MissedThreshold.For(w, options)!;
                if (perRun)
                {
                    // Silence between runs is normal, so there is no not-reporting rule: only successes count. A
                    // workload with no success anywhere in four gaps is new (its rule loads before its first run) or
                    // retired, so it does not alert; New Relic's loss of signal behaves the same way.
                    var success = $"{Runs}{{{selector}, runsignal_outcome=\"success\"}}";
                    Rule("RunSignalMissed", "missed",
                        $"absent_over_time({success}[{Number(missed.Seconds)}s]) and on (job, runsignal_workload) max by (job, runsignal_workload) (max_over_time({success}[{Number(missed.Seconds * 4)}s]))",
                        "0s",
                        $"{w.Name} has not succeeded for longer than its schedule ({w.Schedule}) allows: {DurationText.Format(missed.Interval)} between runs plus {DurationText.Format(missed.Grace)} grace.");
                    if (w.FailureRateThreshold is null)
                        Rule("RunSignalFailed", "failed", $"{Grew($"{Runs}{{{selector}, runsignal_outcome=\"failure\"}}", "5m")} > 0", "0s",
                            $"A run of {w.Name} failed.");
                }
                else
                {
                    Rule("RunSignalMissed", "missed",
                        $"max by (job, runsignal_workload) ({SinceSuccess}{{{selector}}}) > {Number(missed.Seconds)}",
                        "1m",
                        $"{w.Name} has not succeeded for longer than its schedule ({w.Schedule}) allows: {DurationText.Format(missed.Interval)} between runs plus {DurationText.Format(missed.Grace)} grace.");
                    Rule("RunSignalNotReporting", "not-reporting",
                        $"absent_over_time({SinceSuccess}{{{selector}}}[{notReporting}])",
                        "0s",
                        $"{w.Name} has reported nothing for {notReporting}: the service is down or not exporting.");
                    if (w.FailureRateThreshold is null)
                        Rule("RunSignalFailed", "failed", Increased($"{Runs}{{{selector}, runsignal_outcome=\"failure\"}}", "5m"), "0s",
                            $"A run of {w.Name} failed.");
                }
            }
            catch (FormatException ex)
            {
                warnings.Add($"{w.Name}: no missed-run rule, because the schedule could not be read. {ex.Message}");
            }
        }

        if (w.ExpectEverySeconds is not null && perRun)
        {
            warnings.Add($"{w.Name}: no stalled rule, because heartbeats need a long-running process and the workload reports per run.");
        }
        else if (w.ExpectEverySeconds is { } expectEvery)
        {
            Rule("RunSignalStalled", "stalled",
                $"max by (job, runsignal_workload) ({SinceHeartbeat}{{{selector}}}) > {Number(expectEvery)}",
                "1m",
                $"{w.Name} has not sent a heartbeat for longer than {DurationText.Format(TimeSpan.FromSeconds(expectEvery))}.");
            if (w.Schedule is null)
                Rule("RunSignalNotReporting", "not-reporting",
                    $"absent_over_time({SinceHeartbeat}{{{selector}}}[{notReporting}])",
                    "0s",
                    $"{w.Name} has reported nothing for {notReporting}: the service is down or not exporting.");
        }

        if (w.MaxDurationSeconds is { } maxDuration)
        {
            // Histograms only know their buckets, so the alert uses the first bucket at or above the limit.
            var bucket = RunSignalTelemetry.DurationBuckets.Where(b => b >= maxDuration).Cast<double?>().FirstOrDefault();
            if (bucket is { } le)
            {
                Rule("RunSignalOverrun", "overrun",
                    $"{Grew($"{DurationBucket}{{{selector}, le=\"+Inf\"}}", "5m")} - {Grew($"{DurationBucket}{{{selector}, le=\"{Number(le)}\"}}", "5m")} > 0",
                    "0s",
                    $"A run of {w.Name} took longer than {DurationText.Format(TimeSpan.FromSeconds(le))} (limit {DurationText.Format(TimeSpan.FromSeconds(maxDuration))}, rounded up to a histogram bucket).");
            }
            else
            {
                warnings.Add($"{w.Name}: no overrun rule, because {maxDuration}s is above the largest duration bucket. The hung rule still applies.");
            }

            // The gauge is exact, so unlike overrun it needs no bucket rounding.
            Rule("RunSignalHung", "hung",
                $"max by (job, runsignal_workload) ({ActiveRunAge}{{{selector}}}) > {Number(maxDuration)}",
                "1m",
                $"A run of {w.Name} has been running for longer than {DurationText.Format(TimeSpan.FromSeconds(maxDuration))} and has not finished: it may be hung, or the code never ends the run.");
        }

        if (w.MinProcessed is { } minProcessed)
        {
            Rule("RunSignalLowOutput", "low-output",
                $"{Grew($"{Items}{{{selector}, runsignal_item_result=\"processed\"}}", "1h")} / {Grew($"{Runs}{{{selector}, runsignal_outcome=\"success\"}}", "1h")} < {minProcessed}",
                "0s",
                $"Successful runs of {w.Name} processed fewer than {minProcessed} items on average in the last hour.");
        }

        if (w.FailureRateThreshold is { } rate)
        {
            var percent = (rate * 100).ToString("0.#", CultureInfo.InvariantCulture) + "%";
            Rule("RunSignalFailureRate", "failure-rate",
                $"{Grew($"{Runs}{{{selector}, runsignal_outcome=\"failure\"}}", "15m")} / {Grew($"{Runs}{{{selector}, runsignal_outcome=~\"success|failure\"}}", "15m")} > {Number(rate)}",
                "0s",
                $"More than {percent} of the runs of {w.Name} failed in the last 15 minutes.");
            Rule("RunSignalItemFailureRate", "item-failure-rate",
                $"{Grew($"{Items}{{{selector}, runsignal_item_result=\"failed\"}}", "15m")} / {Grew($"{Items}{{{selector}}}", "15m")} > {Number(rate)}",
                "0s",
                $"More than {percent} of the items {w.Name} handled failed in the last 15 minutes.");
        }

        if (count == 0 && !warnings.Any(x => x.StartsWith(w.Name + ":", StringComparison.Ordinal)))
            warnings.Add($"{w.Name}: no rules, because it has no expectations.");
    }

    // A counter that went up within the window. increase() cannot see the first sample of a new series, and a
    // failure counter series is created by its first failure, so a series that is new in the window counts too.
    private static string Increased(string series, string window) =>
        $"{By} (increase({series}[{window}])) > 0 or {By} ({series} unless {series} offset {window}) > 0";

    private static void Append(StringBuilder yaml, AlertRule rule)
    {
        var (service, w, alert, kind, expr, forDuration, summary) = rule;
        yaml.Append("      - alert: ").AppendLine(alert)
            .Append("        expr: ").AppendLine(Yaml(expr))
            .Append("        for: ").AppendLine(forDuration)
            .AppendLine("        labels:")
            .Append("          severity: ").AppendLine(w.Severity.ToString().ToLowerInvariant())
            .Append("          runsignal_alert: ").AppendLine(kind)
            .Append("          runsignal_workload: ").AppendLine(Yaml(w.Name));
        if (w.Owner is { } owner)
            yaml.Append("          owner: ").AppendLine(Yaml(owner));
        yaml.AppendLine("        annotations:")
            .Append("          summary: ").AppendLine(Yaml($"{service}/{w.Name}: {kind}"))
            .Append("          description: ").AppendLine(Yaml(summary));
        if (w.RunbookUrl is { } runbook)
            yaml.Append("          runbook_url: ").AppendLine(Yaml(runbook));
    }

    // PromQL string literal.
    private static string Label(string value) => "\"" + value.Replace("\\", "\\\\").Replace("\"", "\\\"") + "\"";

    // YAML single-quoted scalar: only the quote needs escaping.
    private static string Yaml(string value) => "'" + value.Replace("'", "''") + "'";

    private static string Number(double value) => value.ToString("0.############", CultureInfo.InvariantCulture);
}
