using System.Security.Cryptography;
using System.Text;
using RunSignal.Alerting;

namespace RunSignal.Prometheus;

/// <summary>
/// Writes RunSignal's alerts as a Grafana alerting provisioning file, for Grafana-managed alert rules (Grafana Cloud
/// or self-hosted Grafana with a Prometheus data source) instead of a Prometheus ruler. The queries are the same PromQL
/// as <see cref="PrometheusRules"/>, so both fire at the same thresholds.
/// </summary>
public static class GrafanaAlerting
{
    /// <summary>
    /// Generates the provisioning file (<c>apiVersion: 1</c>, one rule group per service). Load it from Grafana's
    /// <c>provisioning/alerting</c> directory, or convert it with Grafana's API. <paramref name="warnings"/> lists
    /// expectations that produced no rule, and why.
    /// </summary>
    /// <param name="manifests">The workload manifests.</param>
    /// <param name="options">Grace periods and the schedules' time zone.</param>
    /// <param name="datasourceUid">The uid of the Prometheus data source that receives RunSignal's metrics.</param>
    /// <param name="folder">The Grafana folder for the rules.</param>
    /// <param name="warnings">Expectations that produced no rule.</param>
    public static string Generate(IEnumerable<WorkloadManifest> manifests, AlertOptions options, string datasourceUid, string folder, out IReadOnlyList<string> warnings)
    {
        ArgumentNullException.ThrowIfNull(manifests);
        ArgumentException.ThrowIfNullOrWhiteSpace(datasourceUid);
        ArgumentException.ThrowIfNullOrWhiteSpace(folder);
        var notes = new List<string>();
        var yaml = new StringBuilder()
            .AppendLine("# Generated by RunSignal from workload manifests. Do not edit: regenerate with `runsignal export grafana-alerts`.")
            .AppendLine("apiVersion: 1")
            .AppendLine("groups:");

        foreach (var group in manifests.GroupBy(m => m.Service, StringComparer.Ordinal))
        {
            var rules = PrometheusRules.Rules(group, options, out var found);
            notes.AddRange(found);
            if (rules.Count == 0)
                continue;

            yaml.AppendLine("  - orgId: 1")
                .Append("    name: ").AppendLine(Yaml($"runsignal-{group.Key}"))
                .Append("    folder: ").AppendLine(Yaml(folder))
                .AppendLine("    interval: 1m")
                .AppendLine("    rules:");
            foreach (var rule in rules)
                Append(yaml, rule, datasourceUid);
        }

        warnings = notes;
        return yaml.ToString();
    }

    private static void Append(StringBuilder yaml, AlertRule rule, string datasourceUid)
    {
        var w = rule.Workload;
        yaml.Append("      - uid: ").AppendLine(Uid(rule))
            .Append("        title: ").AppendLine(Yaml($"{rule.Service}/{w.Name}: {rule.Kind}"))
            .AppendLine("        condition: C")
            .AppendLine("        data:")
            // A: the rule's PromQL. Like a Prometheus rule, it returns a series only while the condition holds.
            .AppendLine("          - refId: A")
            .AppendLine("            relativeTimeRange: { from: 600, to: 0 }")
            .Append("            datasourceUid: ").AppendLine(Yaml(datasourceUid))
            .AppendLine("            model:")
            .AppendLine("              refId: A")
            .Append("              expr: ").AppendLine(Yaml(rule.Expr))
            .AppendLine("              instant: true")
            .AppendLine("              range: false")
            // C: fire for any series A returns. The values are never negative (ages, counts, ratios, 1 for absent).
            .AppendLine("          - refId: C")
            .AppendLine("            datasourceUid: __expr__")
            .AppendLine("            model:")
            .AppendLine("              refId: C")
            .AppendLine("              type: threshold")
            .AppendLine("              expression: A")
            .AppendLine("              conditions:")
            .AppendLine("                - evaluator: { type: gt, params: [-1] }")
            // No series means the condition does not hold, as with a Prometheus rule.
            .AppendLine("        noDataState: OK")
            .AppendLine("        execErrState: Error")
            .Append("        for: ").AppendLine(rule.For)
            .AppendLine("        labels:")
            .Append("          severity: ").AppendLine(w.Severity.ToString().ToLowerInvariant())
            .Append("          runsignal_alert: ").AppendLine(rule.Kind)
            .Append("          runsignal_workload: ").AppendLine(Yaml(w.Name));
        if (w.Owner is { } owner)
            yaml.Append("          owner: ").AppendLine(Yaml(owner));
        yaml.AppendLine("        annotations:")
            .Append("          summary: ").AppendLine(Yaml($"{rule.Service}/{w.Name}: {rule.Kind}"))
            .Append("          description: ").AppendLine(Yaml(rule.Description));
        if (w.RunbookUrl is { } runbook)
            yaml.Append("          runbook_url: ").AppendLine(Yaml(runbook));
    }

    // Grafana identifies rules by uid (at most 40 characters). The same service, workload and alert always give the
    // same uid, so provisioning again updates the rule instead of adding a copy. The alert name keeps not-reporting
    // rules apart from the missed rule of the same workload.
    private static string Uid(AlertRule rule)
    {
        var hash = SHA256.HashData(Encoding.UTF8.GetBytes($"{rule.Service}\n{rule.Workload.Name}\n{rule.Alert}"));
        return "runsignal-" + Convert.ToHexString(hash, 0, 12).ToLowerInvariant();
    }

    private static string Yaml(string value) => "'" + value.Replace("'", "''") + "'";
}
