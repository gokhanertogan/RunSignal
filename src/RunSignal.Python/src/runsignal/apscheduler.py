"""
APScheduler 3 integration: records every job execution as a run of its workload, with no code in your jobs, and
registers cron-triggered jobs with their schedules, so a job that never fires still gets a missed alert.

    from runsignal.apscheduler import instrument

    scheduler = BackgroundScheduler()
    scheduler.add_job(generate_invoices, "cron", hour=2, id="nightly-invoice")
    instrument(scheduler, workloads={"nightly-invoice": {"max_duration": "30m", "severity": "critical"}})
    scheduler.start()
"""

from __future__ import annotations

import re
import warnings
from typing import Any, Mapping

from apscheduler.events import EVENT_JOB_ADDED, JobEvent
from apscheduler.job import Job
from apscheduler.schedulers.base import BaseScheduler
from apscheduler.triggers.cron import CronTrigger

from ._naming import to_workload_name
from ._registry import Workload, WorkloadRegistry, default_registry

__all__ = ["instrument", "cron_of", "workload_name_of"]

_GENERATED_ID = re.compile(r"^[0-9a-f]{32}$")
_DAYS = {"mon": 1, "tue": 2, "wed": 3, "thu": 4, "fri": 5, "sat": 6, "sun": 7}
_MARK = "__runsignal_workload__"


def workload_name_of(job: Job) -> str:
    """The workload a job runs as: its ``id``, or its ``name`` when the id was generated by APScheduler."""
    return to_workload_name(job.name if _GENERATED_ID.match(job.id) else job.id)


def _day_of_week(expression: str) -> str:
    # APScheduler counts days from Monday = 0; Unix cron from Sunday = 0, with 7 also Sunday. Monday..Sunday become
    # 1..7, so ranges such as sat-sun stay ascending.
    def value(v: str) -> str:
        v = v.lower()
        if v in _DAYS:
            return str(_DAYS[v])
        if v.isdigit():
            return str(int(v) + 1)
        raise ValueError(v)

    parts = []
    for token in expression.split(","):
        base, _, step = token.partition("/")
        if base == "*":
            base = "1-7" if step else "*"
        else:
            base = "-".join(value(v) for v in base.split("-"))
        parts.append(f"{base}/{step}" if step else base)
    return ",".join(parts)


def cron_of(trigger: CronTrigger) -> str | None:
    """A cron trigger as a cron expression, 5 fields or 6 with seconds first, or None if it uses fields cron
    cannot express (``year``, ``week``, or days such as ``1st mon``)."""
    fields = {f.name: str(f) for f in trigger.fields}
    if fields["year"] != "*" or fields["week"] != "*":
        return None
    day = "L" if fields["day"] == "last" else fields["day"]
    if re.search(r"[a-zA-KM-Z]", day):
        return None
    try:
        day_of_week = _day_of_week(fields["day_of_week"])
    except ValueError:
        return None
    cron = f"{fields['minute']} {fields['hour']} {day} {fields['month']} {day_of_week}"
    return cron if fields["second"] == "0" else f"{fields['second']} {cron}"


class _Instrumentation:
    def __init__(self, scheduler: BaseScheduler, registry: WorkloadRegistry, workloads: Mapping[str, Mapping[str, Any]]) -> None:
        self.scheduler = scheduler
        self.registry = registry
        self.workloads = workloads

    def register(self, job: Job) -> Workload:
        name = workload_name_of(job)
        options = dict(self.workloads.get(name, {}))
        if isinstance(job.trigger, CronTrigger) and "schedule" not in options:
            cron = cron_of(job.trigger)
            if cron is not None:
                options["schedule"] = cron
            else:
                warnings.warn(f"runsignal: the trigger of job '{job.id}' cannot be written as cron, so it gets no missed alert.",
                              stacklevel=3)
        workload = self.registry.get_or_add(name, **options)

        if getattr(job.func, _MARK, None) is None:
            wrapped = workload.monitor(job.func)
            setattr(wrapped, _MARK, workload)
            try:
                self.scheduler.modify_job(job.id, getattr(job, "_jobstore_alias", None), func=wrapped)
            except Exception as error:  # a persistent job store cannot store a wrapper it cannot import
                warnings.warn(f"runsignal: could not instrument job '{job.id}' ({error}). Decorate its function with "
                              f"@registry.monitor('{name}') instead.", stacklevel=3)
        return workload

    def on_added(self, event: JobEvent) -> None:
        job = self.scheduler.get_job(event.job_id, event.jobstore)
        if job is not None:
            self.register(job)


def instrument(
    scheduler: BaseScheduler,
    *,
    registry: WorkloadRegistry | None = None,
    workloads: Mapping[str, Mapping[str, Any]] | None = None,
) -> list[Workload]:
    """Records every run of every job of ``scheduler``, now and added later: success, failure with the exception's
    type, and duration. Cron-triggered jobs are registered with their schedule. ``workloads`` maps workload names
    to expectations, such as ``{"nightly-invoice": {"max_duration": "30m"}}``. Time zones are not carried over:
    pass ``--time-zone`` to the CLI if the triggers use one.

    Jobs in a persistent job store (SQLAlchemy, Redis, MongoDB) cannot hold a wrapped function; decorate their
    functions with ``@registry.monitor(name)`` instead, and this still registers their schedules.
    """
    handler = _Instrumentation(scheduler, registry or default_registry, workloads or {})
    found = [handler.register(job) for job in scheduler.get_jobs()]
    scheduler.add_listener(handler.on_added, EVENT_JOB_ADDED)
    return found
